// 字段映射：根据语言选择对象里的中文/英文字段
function pick(obj, field, lang) {
  if (!obj) return '';
  const en = obj[field + 'En'];
  if (lang === 'en') return (en && en.trim()) ? en : (obj[field] || '');
  return obj[field] || en || '';
}

